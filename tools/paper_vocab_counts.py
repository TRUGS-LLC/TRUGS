"""Generate the paper's vocabulary macros from the language graph."""

# <trl>
# PROCESS vocabulary_counting SHALL READ FILE language_trug THEN PRODUCE DATA macros.
# </trl>
from __future__ import annotations

import json
from collections import Counter
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
PART_NAMES = {
    "noun": "Nouns",
    "verb": "Verbs",
    "adjective": "Adjectives",
    "adverb": "Adverbs",
    "preposition": "Prepositions",
    "conjunction": "Conjunctions",
    "article": "Articles",
    "pronoun": "Pronouns",
    "level_prefix": "LevelPrefixes",
}
SOURCES = ("computation", "law", "shared")
VERB_GROUPS = (
    "transform",
    "move",
    "obligate",
    "permit",
    "prohibit",
    "control",
    "bind",
    "resolve",
)


# <trl>
# FUNCTION vocabulary_macros SHALL MAP RECORD language TO DATA macros THEN RETURN DATA macros.
# </trl>
# ---
# FUNCTION vocabulary_macros SHALL MAP RECORD language TO DATA macros THEN RETURN DATA macros.
def vocabulary_macros(language: dict[str, Any]) -> dict[str, str]:
    """Count word-key presence, following the root's category order.

    Empty sources count as shared. Percentages use exact integer arithmetic
    for half-up rounding; only empty part/source cells use a dash.
    """
    nodes = language["nodes"]
    by_id = {node["id"]: node for node in nodes}
    roots = [node for node in nodes if node["parent_id"] is None]
    if len(roots) != 1:
        raise ValueError("the language graph must have one root")
    parts = [by_id[key]["properties"]["speech"] for key in roots[0]["contains"]]
    if len(set(parts)) != len(parts):
        raise ValueError("duplicate speech category")
    words = [node["properties"] for node in nodes if "word" in node["properties"]]
    total = len(words)
    if not total:
        raise ValueError("the vocabulary has no words")
    cells: Counter[tuple[str, str]] = Counter()
    groups: Counter[str] = Counter()
    for word in words:
        speech = word["speech"]
        source = word["source"] or "shared"
        if speech not in parts or source not in SOURCES:
            raise ValueError("word has an unknown speech category or source")
        cells[speech, source] += 1
        if speech == "verb":
            group = word["subcategory"]
            if group not in VERB_GROUPS:
                raise ValueError("word has an unknown verb group")
            groups[group] += 1
    macros = {
        "VocabVersion": str(language["version"]),
        "VocabTotal": str(total),
        "VocabParts": str(len({word["speech"] for word in words})),
    }
    for source in SOURCES:
        count = sum(cells[part, source] for part in parts)
        name = "Vocab" + source.title()
        macros[name] = str(count)
        macros[name + "Pct"] = str((200 * count + total) // (2 * total))
    for part in parts:
        name = "Vocab" + PART_NAMES[part]
        macros[name] = str(sum(cells[part, source] for source in SOURCES))
        for source in SOURCES:
            count = cells[part, source]
            macros[name + source.title()] = str(count) if count else "---"
    for group in VERB_GROUPS:
        macros["VocabVerbs" + group.title()] = str(groups[group])
    return macros


# <trl>
# FUNCTION render_macros SHALL MAP DATA macros TO DATA text THEN RETURN DATA text.
# </trl>
# ---
# FUNCTION render_macros SHALL MAP DATA macros TO DATA text THEN RETURN DATA text.
def render_macros(macros: dict[str, str]) -> str:
    return "% Generated by tools/paper_vocab_counts.py; do not edit.\n" + "".join(
        f"\\newcommand{{\\{name}}}{{{value}}}\n" for name, value in macros.items()
    )


# <trl>
# FUNCTION main SHALL READ FILE language_trug THEN WRITE FILE vocab_counts.
# </trl>
# ---
# FUNCTION main SHALL READ FILE language_trug THEN WRITE FILE vocab_counts.
def main() -> None:
    language = json.loads((ROOT / "TRUGS_LANGUAGE/language.trug.json").read_text())
    macros = vocabulary_macros(language)
    output = ROOT / "PAPER/generated/vocab_counts.tex"
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(render_macros(macros), encoding="utf-8")
    for name, value in macros.items():
        print(f"{name}: {value}")
    print(f"Wrote {output.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
